export function translate(lang: Lang, text: string, vars?: Record<string, string | number>): string {
  let out = lang === "ur" ? (UR[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}

